use crate::model::ProtocolModel;

fn field_name(index: usize, field: &crate::fields::FieldInterpretation) -> String {
    match field {
        crate::fields::FieldInterpretation::Constant { .. } => {
            if index == 0 {
                "header".to_string()
            } else {
                format!("reserved_{}", index - 1)
            }
        }
        crate::fields::FieldInterpretation::CounterLike { .. } => "counter".to_string(),
        _ => format!("field_{}", index),
    }
}

pub fn generate_rust(model: &ProtocolModel, frames: &[Vec<u8>]) -> String {
    let mut out = String::new();

    out.push_str("// Generated by Babelfish\n");
    out.push_str("// WARNING: Review all ambiguous interpretations before production use.\n\n");

    // ------------------------------------------------------------
    // Packet structure
    // ------------------------------------------------------------

    out.push_str("#[derive(Debug)]\n");
    out.push_str("pub struct Packet {\n");

    for (index, field) in model.fields.iter().enumerate() {
        let name = field_name(index, field);
        out.push_str(&format!("    pub {}: u8,\n", name));
    }

    out.push_str("}\n\n");

    // ------------------------------------------------------------
    // Checksum implementation
    // ------------------------------------------------------------

    if model.checksum.algorithm == "CRC8" {
        out.push_str(
            r#"fn crc8(data: &[u8]) -> u8 {
    let mut crc = 0u8;

    for &byte in data {
        crc ^= byte;

        for _ in 0..8 {
            if crc & 0x80 != 0 {
                crc = (crc << 1) ^ 0x07;
            } else {
                crc <<= 1;
            }
        }
    }

    crc
}

"#,
        );
    }

    // ------------------------------------------------------------
    // Parser
    // ------------------------------------------------------------

    out.push_str("pub fn parse_frame(frame: &[u8]) -> Result<Packet, &'static str> {\n");

    let required_length = model.checksum.checksum_end.max(model.checksum.coverage_end);

    out.push_str(&format!("    if frame.len() != {} {{\n", required_length));
    out.push_str("        return Err(\"invalid frame length\");\n");
    out.push_str("    }\n\n");

    // ------------------------------------------------------------
    // Framing
    // ------------------------------------------------------------

    out.push_str(&format!(
        "    // Detected framing: {}\n",
        model.framing.kind
    ));

    if model.framing.kind == "prefix [7E, 10]" {
        out.push_str(
            r#"    if frame[0] != 0x7E || frame[1] != 0x10 {
        return Err("invalid frame prefix");
    }

"#,
        );
    }

    // ------------------------------------------------------------
    // Checksum
    // ------------------------------------------------------------

    out.push_str(&format!(
        "    // Detected checksum: {}\n",
        model.checksum.algorithm
    ));

    out.push_str(&format!(
        "    // Coverage: bytes[{}..{}]\n",
        model.checksum.coverage_start, model.checksum.coverage_end
    ));

    out.push_str(&format!(
        "    // Checksum: bytes[{}..{}]\n\n",
        model.checksum.checksum_start, model.checksum.checksum_end
    ));

    if model.checksum.algorithm == "CRC8" {
        out.push_str(&format!(
            "    let expected_crc = crc8(&frame[{}..{}]);\n",
            model.checksum.coverage_start, model.checksum.coverage_end
        ));

        out.push_str(&format!(
            "    if frame[{}] != expected_crc {{\n",
            model.checksum.checksum_start
        ));

        out.push_str("        return Err(\"CRC8 validation failed\");\n");
        out.push_str("    }\n\n");
    }

    // ------------------------------------------------------------
    // Field extraction
    // ------------------------------------------------------------

    for (index, field) in model.fields.iter().enumerate() {
        let name = field_name(index, field);
        let position = model.checksum.coverage_start + index;

        out.push_str(&format!("    let {} = frame[{}];\n", name, position));
    }

    out.push_str("\n    Ok(Packet {\n");

    for (index, field) in model.fields.iter().enumerate() {
        let name = field_name(index, field);
        out.push_str(&format!("        {},\n", name));
    }

    out.push_str("    })\n");
    out.push_str("}\n");

    // ------------------------------------------------------------
    // Ambiguity information
    // ------------------------------------------------------------

    if model.evidence.ambiguous {
        out.push_str(
            r#"

// WARNING: Protocol interpretation is ambiguous.
//
// Babelfish found competing multi-byte interpretations
// with equal evidence. Do not select one without additional
// protocol evidence.
//
// Candidates:
"#,
        );

        for field in &model.multi_byte_fields {
            out.push_str(&format!(
                "//   bytes[{}..{}] -> {:?}, score {:.2}\n",
                field.start,
                field.start + field.width,
                field.kind,
                field.score
            ));
        }

        out.push_str(
            r#"//
// Do not assume a unique multi-byte interpretation
// without additional protocol evidence.
"#,
        );
    }

    // ------------------------------------------------------------
    // Generated parser tests
    // ------------------------------------------------------------

    if let Some(frame) = frames.first() {
        out.push_str("\n\n#[cfg(test)]\nmod tests {\n    use super::*;\n\n");

        // Test 1: actual captured frame
        out.push_str("    #[test]\n");
        out.push_str("    fn parses_real_frame() {\n");
        out.push_str("        let frame = [");

        for (index, byte) in frame.iter().enumerate() {
            if index > 0 {
                out.push_str(", ");
            }

            out.push_str(&format!("0x{:02X}", byte));
        }

        out.push_str(
            "];\n\n\
                     let packet = parse_frame(&frame)\n\
                         .expect(\"real captured frame should parse\");\n\n",
        );

        for (index, field) in model.fields.iter().enumerate() {
            let name = field_name(index, field);
            let position = model.checksum.coverage_start + index;

            if position < frame.len() {
                out.push_str(&format!(
                    "        assert_eq!(packet.{}, 0x{:02X});\n",
                    name, frame[position]
                ));
            }
        }

        out.push_str(
            "    }\n\n\
             \n",
        );

        // Test 2: corrupted checksum
        out.push_str("    #[test]\n");
        out.push_str("    fn rejects_bad_crc() {\n");
        out.push_str("        let frame = [");

        for (index, byte) in frame.iter().enumerate() {
            if index > 0 {
                out.push_str(", ");
            }

            let value = if index == model.checksum.checksum_start {
                byte.wrapping_add(1)
            } else {
                *byte
            };

            out.push_str(&format!("0x{:02X}", value));
        }

        out.push_str(
            "];\n\n\
                     assert!(\n\
                         parse_frame(&frame).is_err(),\n\
                         \"frame with corrupted checksum should be rejected\"\n\
                     );\n\
                 }\n\n",
        );

        // Test 3: corrupted prefix
        out.push_str("    #[test]\n");
        out.push_str("    fn rejects_bad_prefix() {\n");
        out.push_str("        let frame = [");

        for (index, byte) in frame.iter().enumerate() {
            if index > 0 {
                out.push_str(", ");
            }

            let value = if index == 0 { byte ^ 0xFF } else { *byte };

            out.push_str(&format!("0x{:02X}", value));
        }

        out.push_str(
            "];\n\n\
                     assert!(\n\
                         parse_frame(&frame).is_err(),\n\
                         \"frame with invalid prefix should be rejected\"\n\
                     );\n\
                 }\n\n",
        );

        // Test 4: wrong length
        out.push_str("    #[test]\n");
        out.push_str("    fn rejects_wrong_length() {\n");
        out.push_str("        let frame = [");

        for (index, byte) in frame.iter().take(frame.len().saturating_sub(1)).enumerate() {
            if index > 0 {
                out.push_str(", ");
            }

            out.push_str(&format!("0x{:02X}", byte));
        }

        out.push_str(
            "];\n\n\
                         assert!(\n\
                         parse_frame(&frame).is_err(),\n\
                         \"frame with invalid length should be rejected\"\n\
                     );\n\
                 }\n\
             }\n",
        );
    }

    out
}
